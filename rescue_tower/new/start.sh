#!/usr/bin/env bash
# ============================================================
# 一键启动救援塔总控（树莓派上执行）
# 用法：
#   bash start.sh              # 连接真机（水位/升降台/小船/666.py）
#   bash start.sh --demo       # 离线演示（电脑上也能跑）
# 启动后浏览器打开： http://<树莓派IP>:8080
# ============================================================
cd "$(dirname "$0")"
exec python3 救援总控.py --live --web "$@"
