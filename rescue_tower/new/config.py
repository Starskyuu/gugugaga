#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
智能城市救援塔 —— 总控配置（真机只需要改这个文件）
============================================================
所有 IP、阈值、速度都集中在这里修改，不要到 救援总控.py 里到处找。

目录结构约定（树莓派上保持不动）：
    rescue_tower/
    ├── esp32/           三块 ESP32 固件（烧录用，不参与运行）
    ├── raspberry_pi/    666.py 视觉、best.pt 模型、摄像头标定
    └── new/             本目录：总控 + 配置 + 网页 + 启动脚本
"""

from pathlib import Path

# ============================================================
# 一、文件路径（一般不用改）
# ============================================================

# new/ 的上级就是 rescue_tower/
RPI_DIR = Path(__file__).resolve().parent.parent / "raspberry_pi"

VISION_FILE = RPI_DIR / "vision" / "666.py"
MODEL_FILE = RPI_DIR / "models" / "best.pt"
CALIB_FILE = RPI_DIR / "calibration" / "camera_calibration_usb.json"

# 日志与网页快照都放在 new/logs/ 下（自动创建）
LOG_DIR = Path(__file__).resolve().parent / "logs"
SNAPSHOT_PATH = LOG_DIR / "snapshot.jpg"

# 666.py 启动参数：树莓派上是否打开摄像头画面窗口
#   True  = 树莓派接显示器时调试用
#   False = 后台静默运行（正式运行时推荐）
VISION_SHOW_WINDOW = False

# 666.py 详细日志输出到 new/logs/vision.log（推荐），还是直接打印到终端
VISION_LOG_TO_FILE = True

# ============================================================
# 二、网络（改这里的 IP）
# ============================================================

# 三块板的 IP 看它们串口打印（Thonny 打开后能看到）
BOAT_IP = "192.168.43.14"   # 小船 ESP32 的 IP
LIFT_IP = "192.168.43.21"   # 升降台 ESP32 的 IP

# 船上贴的 ArUco 码编号，必须与 666.py 识别出来的 boat id 一致
BOAT_ID = 0

# ESP32 固件的 HTTP 端口（固件里写死 80）
HTTP_PORT = 80

# 水位板 -> 树莓派 TCP 端口（水位固件里写死 5000，不要改 ESP32 后忘记改这里）
WATER_PORT = 5000

# 666.py -> 总控 的 UDP 状态端口（666.py --state-port 默认 9101）
VISION_PORT = 9101

# 一键网页
WEB_HOST = "0.0.0.0"   # 0.0.0.0 = 局域网内手机/电脑都能访问
WEB_PORT = 8080        # 浏览器打开 http://树莓派IP:8080

# ============================================================
# 三、水位触发（现场拿传感器实测值标定）
# ============================================================

# 总控启动后，取前 N 个有效水位值的中位数当作"干燥基线"
WATER_BASELINE_SAMPLES = 5

# 当前值 >= 基线 + 此数值，算一次"高水位"。
# 水位传感器是 ADC 读数（0~65535），浸水后读数上升，
# 现场先开 --check-water 看干燥/浸水各是多少，再定这个差值。
WATER_DELTA_TRIGGER = 6000

# 连续多少次高水位才真正触发洪水（防止水面晃动误报）
WATER_TRIGGER_COUNT = 3

# 可选：绝对值阈值。例如你知道浸水后读数必然超过 40000，
# 就设 WATER_ABS_TRIGGER = 40000，与"基线+差值"同时生效；不用就 None。
WATER_ABS_TRIGGER = None

# 水位确认持续报警这么久（秒）才启动升台
FLOOD_CONFIRM_S = 1.0

# ============================================================
# 四、场地（与 666.py 保持一致，勿改）
# ============================================================

FIELD_W = 600.0    # 场地宽 mm
FIELD_H = 600.0    # 场地高 mm

# ============================================================
# 五、升降台
# ============================================================

# 发 /U 之后等待这么久（秒），给舵机从最低走到最高的时间。
# 升降台固件没有位置反馈，只能按时间等；现场掐表实测后修改。
LIFT_UP_TIME_SEC = 8.0

# ============================================================
# 六、无人船自动导航
# ============================================================

# 船码中心离人这么近（mm）就宣布"到了"，停船
ARRIVE_DIST_MM = 55.0

# 航向偏差超过这个角度（度）时，整个周期原地转向
TURN_THRESHOLD_DEG = 25.0

# 航向偏差小于这个角度时不加转向修正，避免蛇形
HEADING_DEADBAND_DEG = 8.0

# 距离小于这个值（mm）开始半速靠近，防止冲过头
SLOW_DIST_MM = 150.0

# 控制周期（秒）。小船固件 700ms 收不到命令自动停车，
# 所以这个值必须明显小于 0.7，默认 0.2 很安全。
CONTROL_INTERVAL_SEC = 0.2

# 连续停在目标范围内这么久（秒）才算真到了
ARRIVE_HOLD_S = 0.6

# 视觉状态多久没更新（秒）就认为掉线，立即停船
VISION_TIMEOUT_S = 1.2

# 单次 HTTP 控制超时（秒）
HTTP_TIMEOUT_S = 0.5

# 找人阶段最长等待（秒），超时回到"等待放船"重新确认
SEARCH_TIMEOUT_S = 60.0

# 自动航行阶段最长等待（秒）
NAVIGATE_TIMEOUT_S = 90.0

# 导航时连续失败（视觉掉线/HTTP 不通）这么多次就急停
NAV_MAX_FAILS = 5

# 左右转方向修正：现场试跑发现"想右转船却左转"时，把 1 改成 -1
TURN_SIGN = 1

# 目标（人）从视野消失超过这么久（秒）就回到找人阶段
TARGET_LOST_TIMEOUT_S = 1.5

# ============================================================
# 七、启动视觉的探测
# ============================================================

# 总控启动后先等这么久（秒）看 UDP 9101 有没有数据：
# 有 = 666.py 已经在别处跑着，不再重复启动；没有 = 自动帮启动。
VISION_PROBE_SEC = 2.5
